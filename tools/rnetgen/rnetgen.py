def load(path: Path = SCHEMA) -> dict:
    with path.open("rb") as f:
        return tomllib.load(f)


def schema_hash(s: dict) -> int:
    """16-bit hash of the parsed schema: comments and layout don't change it."""
    canon = json.dumps(s, sort_keys=True, separators=(",", ":")).encode()
    return int.from_bytes(hashlib.sha256(canon).digest()[:2], "big")


