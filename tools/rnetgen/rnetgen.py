#!/usr/bin/env python3
"""Generates every protocol artefact from schema/rnet.toml.

    python3 tools/rnetgen/rnetgen.py           write the outputs
    python3 tools/rnetgen/rnetgen.py --check   exit 1 if a committed output differs

    output                              contents
    lib/rnet/gen/rnet_phy.hpp           physical layer parameters for RadioLib's CC1101 driver
    lib/rnet/gen/rnet_messages.hpp/cpp  message structs, pack/unpack
    tools/rnet_py/rnet_messages.py      Python codec
    docs/generated/messages.md          message tables
    test/vectors/frames.json/hpp        golden frames under the published test key

    acronym  meaning
    rnet     home radio network (this protocol)
    phy      physical layer
    mic      message integrity code: truncated AES-CMAC
    tlv      type-length-value
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SCHEMA_PATH = ROOT / "schema" / "rnet.toml"
BANNER = "GENERATED by tools/rnetgen from schema/rnet.toml. Do not edit."


def load_schema(path: Path = SCHEMA_PATH) -> dict:
    with path.open("rb") as schema_file:
        return tomllib.load(schema_file)


def schema_hash(schema: dict) -> int:
    canonical = json.dumps(schema, sort_keys=True, separators=(",", ":")).encode()
    return int.from_bytes(hashlib.sha256(canonical).digest()[:2], "big")


def emit_phy_hpp(schema: dict) -> str:
    phy = schema["phy"]
    assert phy["modulation"] == "gfsk" and phy["packet_length"] == "variable"
    assert phy["sync_mode"] == "30/32", "RadioLib: 30/32 = 16-bit sync word sent twice (repeatSync)"
    sync_word = phy["sync_word"]
    assert (sync_word >> 8) and (sync_word & 0xFF), "RadioLib rejects a 0x00 sync byte"
    return "\n".join([
        f"// {BANNER}",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace rnet::phy",
        "{",
        f"inline constexpr uint8_t schema_version = {schema['schema_version']};",
        f"inline constexpr uint16_t schema_hash = 0x{schema_hash(schema):04X};",
        f"inline constexpr float frequency_mhz = {phy['frequency_hz'] / 1e6:.4f}f;",
        f"inline constexpr float bit_rate_kbps = {phy['data_rate_bps'] / 1e3:.1f}f;",
        f"inline constexpr float deviation_khz = {phy['deviation_hz'] / 1e3:.1f}f;",
        f"inline constexpr float rx_bandwidth_khz = {phy['rx_bandwidth_hz'] / 1e3:.3f}f;",
        f"inline constexpr uint16_t preamble_bits = {8 * phy['preamble_bytes']};",
        f"inline constexpr uint8_t preamble_quality_threshold_bits = {phy['preamble_quality_threshold_bits']};",
        f"inline constexpr uint8_t sync_word_high = 0x{sync_word >> 8:02X};",
        f"inline constexpr uint8_t sync_word_low = 0x{sync_word & 0xFF:02X};",
        "inline constexpr bool sync_word_sent_twice = true;",
        f"inline constexpr bool crc16_enabled = {str(phy['crc16']).lower()};",
        f"inline constexpr bool whitening_enabled = {str(phy['whitening']).lower()};",
        f"inline constexpr uint8_t max_packet_length = {schema['frame']['max_payload']};",
        f"inline constexpr uint32_t rx_window_ms = {phy['rx_window_ms']};",
        f"inline constexpr uint8_t uplink_jitter_percent = {phy['uplink_jitter_percent']};",
        "} // namespace rnet::phy",
        "",
    ])


#   schema type -> (bytes, C++ type, signed, Python struct format)
FIELD_TYPES = {
    "u8": (1, "uint8_t", False, "B"),
    "u16": (2, "uint16_t", False, "H"),
    "u32": (4, "uint32_t", False, "I"),
    "i8": (1, "int8_t", True, "b"),
    "i16": (2, "int16_t", True, "h"),
    "i32": (4, "int32_t", True, "i"),
    "bits": (1, "uint8_t", False, "B"),
}
FRAME_OVERHEAD_BYTES = 14


def fixed_layout_messages(schema: dict) -> list[tuple[str, dict]]:
    return [
        (name, message)
        for name, message in schema["messages"].items()
        if not message.get("placeholder") and all(field["type"] != "tlv" for field in message.get("fields", []))
    ]


def payload_length(message: dict) -> int:
    return sum(FIELD_TYPES[field["type"]][0] for field in message["fields"])


def check_schema(schema: dict) -> None:
    for name, message in fixed_layout_messages(schema):
        length = payload_length(message)
        if "payload_length" in message:
            assert length == message["payload_length"], (
                f"{name}: fields add up to {length}, payload_length says {message['payload_length']}")
        assert length + FRAME_OVERHEAD_BYTES <= schema["frame"]["max_payload"], (
            f"{name}: {length} + {FRAME_OVERHEAD_BYTES} bytes of frame > one FIFO")
    for name, message in schema["messages"].items():
        if name.startswith("GARDEN_") and message["direction"] == "downlink" and not message.get("placeholder"):
            assert any(field["name"] == "duration_seconds" for field in message["fields"]), (
                f"{name}: garden R-3 needs duration_seconds")


ACRONYM_TABLE = [
    "//",
    "// acronym  meaning",
    "// rnet     home radio network (this protocol)",
    "// mic      message integrity code: truncated AES-CMAC",
    "// ack      acknowledgement",
    "// rx       receive",
    "// rssi     received signal strength indicator",
    "// tlv      type-length-value",
    "//",
]


def cpp_name(message_name: str) -> str:
    return message_name.lower()


def cpp_literal(value: int, cpp_type: str, signed: bool, bits: int) -> str:
    if signed and value >= 1 << (bits - 1):
        value -= 1 << bits
    return f"static_cast<{cpp_type}>({value})" if signed else f"static_cast<{cpp_type}>(0x{value:X}u)"


def invalid_hex(field: dict, size: int) -> str:
    return f"0x{field['invalid'] & ((1 << (8 * size)) - 1):X}" if "invalid" in field and size else ""


def field_chart(message: dict) -> list[str]:
    rows = [("offset", "field", "type", "scale", "unit", "invalid")]
    offset = 0
    for field in message["fields"]:
        size = FIELD_TYPES[field["type"]][0]
        unit = field.get("unit", "") + (f" x {field['convert']}" if "convert" in field else "")
        rows.append((str(offset), field["name"], field["type"], str(field.get("scale", "")), unit,
                     invalid_hex(field, size)))
        offset += size
    widths = [max(len(row[column]) for row in rows) for column in range(len(rows[0]))]
    return ["// " + "  ".join(cell.ljust(width) for cell, width in zip(row, widths)).rstrip() for row in rows]


def emit_messages_hpp(schema: dict) -> str:
    frame = schema["frame"]
    lines = [f"// {BANNER}"] + ACRONYM_TABLE + [
        "#pragma once", "", "#include <cstddef>", "#include <cstdint>", "", "namespace rnet", "{", "",
        f"inline constexpr uint8_t frame_version = {frame['version']};",
        f"inline constexpr std::size_t max_payload = {frame['max_payload']};",
        f"inline constexpr std::size_t mic_length = {frame['mic_length']};",
        "inline constexpr std::size_t header_length_without_ack = 10;",
        f"inline constexpr uint32_t counter_persist_every = {frame['counter_persist_every']};",
        f'inline constexpr char key_label[] = "{frame["key_derivation"]["label"]}";',
        "", "namespace control_bits", "{"]
    for bit_name, bit in frame["control_bits"].items():
        if "width" in bit:
            lines.append(f"inline constexpr uint8_t {bit_name}_shift = {bit['shift']};")
        else:
            lines.append(f"inline constexpr uint8_t {bit_name} = 1u << {bit['shift']};")
    lines += ["} // namespace control_bits", "", "namespace node", "{"]
    for type_name, node_type in schema["node_types"].items():
        lines.append(f"inline constexpr uint8_t {type_name} = 0x{node_type['id']:02X};")
        for constant_name, value in node_type.get("constants", {}).items():
            lines.append(f"inline constexpr uint32_t {type_name}_{constant_name} = {value};")
    lines += ["} // namespace node", ""]
    for enum_name, values in schema["enums"].items():
        lines.append(f"enum class {enum_name} : uint8_t {{")
        lines += [f"    {value_name} = {value}," for value_name, value in values.items()]
        lines += ["};", ""]
    lines += ["namespace config_key", "{"]
    for key_name, key in schema["config_keys"].items():
        lines.append(f"inline constexpr uint8_t {key_name} = 0x{key['id']:02X};")
    lines += ["} // namespace config_key", "", "namespace message_type", "{"]
    for name, message in schema["messages"].items():
        lines.append(f"inline constexpr uint8_t {cpp_name(name)} = 0x{message['id']:02X};")
    lines += ["} // namespace message_type"]
    for name, message in fixed_layout_messages(schema):
        lines += [""] + field_chart(message) + [
            f"struct {cpp_name(name)} {{",
            f"    static constexpr uint8_t id = 0x{message['id']:02X};",
            f"    static constexpr std::size_t length = {payload_length(message)};",
            f"    static constexpr std::size_t field_count = {len(message['fields'])};"]
        for field in message["fields"]:
            size, cpp_type, signed, _ = FIELD_TYPES[field["type"]]
            if "invalid" in field:
                lines.append(f"    static constexpr {cpp_type} {field['name']}_invalid = "
                             f"{cpp_literal(field['invalid'], cpp_type, signed, 8 * size)};")
            for bit_name, position in field.get("bits", {}).items():
                lines.append(f"    static constexpr uint8_t {field['name']}_{bit_name} = 1u << {position};")
        lines.append("")
        for field in message["fields"]:
            initial_value = f" = {field['name']}_invalid" if "invalid" in field else "{}"
            lines.append(f"    {FIELD_TYPES[field['type']][1]} {field['name']}{initial_value};")
        lines += ["", "    std::size_t pack(uint8_t *buffer) const;",
                  "    std::size_t unpack(const uint8_t *buffer, std::size_t buffer_length);", "};"]
    lines += ["", "} // namespace rnet", ""]
    return "\n".join(lines)


def emit_messages_cpp(schema: dict) -> str:
    lines = [f"// {BANNER}", '#include "rnet_messages.hpp"', "", "namespace rnet", "{"]
    for name, message in fixed_layout_messages(schema):
        struct_name = cpp_name(name)
        lines += ["", f"std::size_t {struct_name}::pack(uint8_t *buffer) const", "{"]
        offset = 0
        for field in message["fields"]:
            size, _, signed, _ = FIELD_TYPES[field["type"]]
            source = f"static_cast<uint{8 * size}_t>({field['name']})" if signed else field["name"]
            for byte_index in range(size):
                shift = f" >> {8 * byte_index}" if byte_index else ""
                lines.append(f"    buffer[{offset + byte_index}] = static_cast<uint8_t>({source}{shift});")
            offset += size
        lines += ["    return length;", "}", "",
                  f"std::size_t {struct_name}::unpack(const uint8_t *buffer, std::size_t buffer_length)", "{",
                  f"    *this = {struct_name}{{}};", "    std::size_t fields_read = 0;"]
        offset = 0
        for field in message["fields"]:
            size, cpp_type, _, _ = FIELD_TYPES[field["type"]]
            assembled = " | ".join(
                f"(uint32_t{{buffer[{offset + byte_index}]}} << {8 * byte_index})" if byte_index
                else f"uint32_t{{buffer[{offset}]}}"
                for byte_index in range(size))
            lines += [f"    if (buffer_length < {offset + size}) {{", "        return fields_read;", "    }",
                      f"    {field['name']} = static_cast<{cpp_type}>(static_cast<uint{8 * size}_t>({assembled}));",
                      "    fields_read++;"]
            offset += size
        lines += ["    return fields_read;", "}"]
    lines += ["", "} // namespace rnet", ""]
    return "\n".join(lines)


def emit_python_codec(schema: dict) -> str:
    kept_keys = ("name", "type", "scale", "unit", "invalid", "bits", "convert")
    messages = {
        name: {"id": message["id"], "direction": message["direction"],
               "fields": [{key: field[key] for key in kept_keys if key in field} for field in message["fields"]]}
        for name, message in fixed_layout_messages(schema)
    }
    node_types = {name: {"id": node_type["id"], "constants": node_type.get("constants", {})}
                  for name, node_type in schema["node_types"].items()}
    message_ids = {name: message["id"] for name, message in schema["messages"].items()}
    return f'''"""{BANNER}

Message codec for host tools. Frames, keys and message integrity code: rnet.py.
"""
import struct

SCHEMA_HASH = 0x{schema_hash(schema):04X}
NODE_TYPES = {node_types!r}
ENUMS = {schema["enums"]!r}
MESSAGE_IDS = {message_ids!r}
MESSAGES = {messages!r}
_STRUCT_FORMAT = {{"u8": "B", "u16": "H", "u32": "I", "i8": "b", "i16": "h", "i32": "i", "bits": "B"}}


def pack(name: str, values: dict) -> bytes:
    return b"".join(struct.pack("<" + _STRUCT_FORMAT[field["type"]], values[field["name"]])
                    for field in MESSAGES[name]["fields"])


def unpack(name: str, payload: bytes) -> dict:
    """Raw field values; a short payload leaves later fields out (ADR-0001 D3)."""
    values, offset = {{}}, 0
    for field in MESSAGES[name]["fields"]:
        struct_format = "<" + _STRUCT_FORMAT[field["type"]]
        size = struct.calcsize(struct_format)
        if offset + size > len(payload):
            break
        values[field["name"]] = struct.unpack_from(struct_format, payload, offset)[0]
        offset += size
    return values


def message_name(message_id: int):
    return next((name for name, known_id in MESSAGE_IDS.items() if known_id == message_id), None)
'''


def emit_markdown(schema: dict) -> str:
    lines = [f"<!-- {BANNER} -->", "# rnet messages", "",
             f"Schema version {schema['schema_version']}, hash `0x{schema_hash(schema):04X}`. "
             "Source: `schema/rnet.toml`; layouts are little-endian, physical value = raw × scale.", "",
             "## Node types", "", "| id | name | constants |", "|---|---|---|"]
    for name, node_type in schema["node_types"].items():
        constants = ", ".join(f"`{key}` = {value}" for key, value in node_type.get("constants", {}).items())
        lines.append(f"| 0x{node_type['id']:02X} | `{name}` | {constants} |")
    lines += ["", "## Messages", ""]
    for name, message in schema["messages"].items():
        lines += [f"### 0x{message['id']:02X} `{name}` ({message['direction']})", ""]
        if message.get("placeholder"):
            lines += ["Placeholder: defined when its project's firmware starts.", ""]
            continue
        lines += ["| offset | field | type | scale | unit | invalid | notes |", "|---|---|---|---|---|---|---|"]
        offset = 0
        for field in message["fields"]:
            size = FIELD_TYPES.get(field["type"], (0,))[0]
            notes = field.get("note", "")
            if "bits" in field:
                notes = ", ".join(f"bit {position} `{bit_name}`" for bit_name, position in field["bits"].items())
            if "convert" in field:
                notes = f"× node constant `{field['convert']}`" + (f"; {notes}" if notes else "")
            lines.append(f"| {offset if size else '…'} | `{field['name']}` | {field['type']} | "
                         f"{field.get('scale', '')} | {field.get('unit', '')} | {invalid_hex(field, size)} | {notes} |")
            offset += size
        if any(field["type"] != "tlv" for field in message["fields"]):
            lines.append(f"\n{offset} bytes.")
        lines.append("")
    return "\n".join(lines)


TEST_MASTER_KEY = bytes(range(16))
TEST_NET_ID = 0x5A


def example_values(message: dict) -> dict:
    values = {}
    for index, field in enumerate(message["fields"]):
        size, _, signed, _ = FIELD_TYPES[field["type"]]
        value = (0x5A + 0x3D * index) * 0x01010101 & ((1 << (8 * size)) - 1)
        if signed:
            value -= 1 << (8 * size - 1)
        values[field["name"]] = value
    return values


def vectors(schema: dict) -> dict:
    sys.path.insert(0, str(ROOT / "tools" / "rnet_py"))
    import rnet  # noqa: E402

    sys.path.pop(0)
    node_types = schema["node_types"]
    label = schema["frame"]["key_derivation"]["label"].encode()
    result = {"schema_hash": f"0x{schema_hash(schema):04X}", "master_key": TEST_MASTER_KEY.hex(),
              "keys": [], "payloads": [], "frames": []}
    for node_id, type_name in [(0x0001, "weather_acurite"), (0x1234, "garden"), (0xFFFE, "soil")]:
        key = rnet.derive_node_key(TEST_MASTER_KEY, node_id, node_types[type_name]["id"], label)
        result["keys"].append({"node_id": node_id, "node_type": node_types[type_name]["id"], "key": key.hex()})
    codec = {}
    exec(emit_python_codec(schema), codec)
    for name, message in fixed_layout_messages(schema):
        values = example_values(message)
        result["payloads"].append({"message": name, "values": values, "payload": codec["pack"](name, values).hex()})
    payloads = {entry["message"]: bytes.fromhex(entry["payload"]) for entry in result["payloads"]}
    control_bits = schema["frame"]["control_bits"]
    rx_open = 1 << control_bits["rx_open"]["shift"]
    downlink = 1 << control_bits["downlink"]["shift"]
    cases = [
        ("WEATHER_REPORT uplink", 0x0001, "weather_acurite", 0, 0x00000001, "WEATHER_REPORT", None),
        ("HEALTH uplink, rx_open", 0x0001, "weather_acurite", rx_open, 0x000100FF, "HEALTH", None),
        ("TIME downlink, acks 0x0102", 0x1234, "garden", downlink, 0xFFFFFFFE, "TIME", 0x0102),
    ]
    for description, node_id, type_name, control, counter, message_name, ack_counter in cases:
        key = rnet.derive_node_key(TEST_MASTER_KEY, node_id, node_types[type_name]["id"], label)
        header = rnet.Header(control=control, net_id=TEST_NET_ID, node_id=node_id,
                             node_type=node_types[type_name]["id"], counter=counter,
                             message_type=schema["messages"][message_name]["id"], ack_counter=ack_counter)
        frame = rnet.build_frame(key, header, payloads[message_name])
        result["frames"].append({
            "description": description, "key": key.hex(), "control": control, "net_id": TEST_NET_ID,
            "node_id": node_id, "node_type": node_types[type_name]["id"], "counter": counter,
            "message": message_name, "ack_counter": ack_counter, "payload": payloads[message_name].hex(),
            "frame": frame.hex()})
    return result


def emit_vectors_json(schema: dict) -> str:
    return json.dumps(vectors(schema), indent=2) + "\n"


def cpp_byte_list(hex_text: str) -> str:
    return "{" + ", ".join(f"0x{byte:02X}" for byte in bytes.fromhex(hex_text)) + "}"


def emit_vectors_hpp(schema: dict) -> str:
    golden = vectors(schema)
    lines = [f"// {BANNER}"] + ACRONYM_TABLE + [
        "#pragma once", "", "#include <array>", "#include <cstdint>", "#include <vector>", "",
        "namespace vectors", "{",
        f"inline const std::array<uint8_t, 16> master_key = {cpp_byte_list(golden['master_key'])};", "",
        "struct derived_key {", "    uint16_t node_id;", "    uint8_t node_type;", "    std::array<uint8_t, 16> key;",
        "};", "inline const derived_key derived_keys[] = {"]
    for key in golden["keys"]:
        lines.append(f"    {{0x{key['node_id']:04X}, 0x{key['node_type']:02X}, {cpp_byte_list(key['key'])}}},")
    lines += ["};", "", "inline constexpr int32_t no_ack = -1;", "", "struct frame {", "    const char *description;",
              "    std::array<uint8_t, 16> key;", "    uint8_t control;", "    uint8_t net_id;", "    uint16_t node_id;",
              "    uint8_t node_type;", "    uint32_t counter;", "    uint8_t message_type;",
              "    int32_t ack_counter;", "    std::vector<uint8_t> payload;", "    std::vector<uint8_t> bytes;", "};",
              "inline const frame frames[] = {"]
    for frame in golden["frames"]:
        ack_counter = frame["ack_counter"] if frame["ack_counter"] is not None else "no_ack"
        lines.append(
            f'    {{"{frame["description"]}", {cpp_byte_list(frame["key"])}, 0x{frame["control"]:02X}, '
            f'0x{frame["net_id"]:02X}, 0x{frame["node_id"]:04X}, 0x{frame["node_type"]:02X}, '
            f'0x{frame["counter"]:08X}, 0x{schema["messages"][frame["message"]]["id"]:02X}, {ack_counter}, '
            f'{cpp_byte_list(frame["payload"])}, {cpp_byte_list(frame["frame"])}}},')
    lines += ["};", "} // namespace vectors", ""]
    return "\n".join(lines)


def home_assistant_fields(message: dict) -> list[dict]:
    fields, offset = [], 0
    for field in message["fields"]:
        size = FIELD_TYPES[field["type"]][0]
        if "home_assistant" in field and "unit" in field:
            entry = {"name": field["name"], "offset": offset, "type": field["type"], "unit": field["unit"],
                     "home_assistant": field["home_assistant"]}
            if "scale" in field:
                entry["scale"] = field["scale"]
            if "convert" in field:
                entry["convert"] = field["convert"]
            if "invalid" in field:
                entry["invalid"] = field["invalid"]
            fields.append(entry)
        offset += size
    return fields


def emit_esphome_tables(schema: dict) -> str:
    lines = [f"# {BANNER}", "", f"SCHEMA_HASH = 0x{schema_hash(schema):04X}", "", "NODE_TYPES = {"]
    lines += [f'    "{name}": 0x{node_type["id"]:02X},' for name, node_type in schema["node_types"].items()]
    lines += ["}", "", "NODE_TYPE_CONSTANTS = {"]
    lines += [f'    "{name}": {node_type.get("constants", {})!r},' for name, node_type in schema["node_types"].items()]
    lines += ["}", "", "UPLINK_MESSAGES = ["]
    for name, message in fixed_layout_messages(schema):
        fields = home_assistant_fields(message)
        if message["direction"] != "uplink" or not fields:
            continue
        lines.append(f'    {{"name": "{name}", "id": 0x{message["id"]:02X}, "node_types": {message["node_types"]!r},')
        lines.append('     "fields": [')
        lines += [f"         {field!r}," for field in fields]
        lines.append("     ]},")
    lines += ["]", ""]
    return "\n".join(lines)


def outputs(schema: dict) -> dict[Path, str]:
    check_schema(schema)
    return {
        ROOT / "lib/rnet/gen/rnet_phy.hpp": emit_phy_hpp(schema),
        ROOT / "lib/rnet/gen/rnet_messages.hpp": emit_messages_hpp(schema),
        ROOT / "lib/rnet/gen/rnet_messages.cpp": emit_messages_cpp(schema),
        ROOT / "tools/rnet_py/rnet_messages.py": emit_python_codec(schema),
        ROOT / "docs/generated/messages.md": emit_markdown(schema),
        ROOT / "test/vectors/frames.json": emit_vectors_json(schema),
        ROOT / "test/vectors/frames.hpp": emit_vectors_hpp(schema),
        ROOT / "esphome/components/radio_net/rnet_tables.py": emit_esphome_tables(schema),
    }


def main(arguments: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if committed outputs differ")
    check_only = parser.parse_args(arguments).check
    stale = []
    for path, text in outputs(load_schema()).items():
        if check_only:
            if not path.exists() or path.read_text() != text:
                stale.append(path.relative_to(ROOT))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
            print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        print("stale generated files (run tools/rnetgen/rnetgen.py):", *stale, sep="\n  ")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
